def load_from_existing_dataset(path, max_samples=100000):
    """Load and process samples from existing dataset."""
    if not os.path.exists(path):
        return []

    print(f"Loading from {path}...")

    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    if 'data' in data:
        raw_data = data['data']
    else:
        raw_data = data

    samples = []
    for item in tqdm(raw_data, desc="Processing"):
        hanzi = item.get('hanzi', '')
        result = process_sample(hanzi)
        if result:
            samples.append(result)
            if len(samples) >= max_samples:
                break

    return samples


def create_dataset(output_path='hmm_dataset.json', max_samples=200000):
    """Create HMM training dataset."""
    print("="*60)
    print("CREATING HMM DATASET")
    print("="*60)

    all_samples = []
    seen = set()

    # Add common phrases
    print("\n[1/3] Adding common phrases...")
    common = create_common_phrases()
    for s in common:
        key = s['hanzi']
        if key not in seen:
            seen.add(key)
            all_samples.append(s)
    print(f"  Added {len(common)} common phrases")

    # Load from phrase dataset
    print("\n[2/3] Loading from phrase dataset...")
    phrase_samples = load_from_existing_dataset('pinyin_phrase_dataset.json', max_samples // 2)
    for s in phrase_samples:
        key = s['hanzi']
        if key not in seen:
            seen.add(key)
            all_samples.append(s)
    print(f"  Total: {len(all_samples)} samples")

    # Load from sentence dataset
    print("\n[3/3] Loading from sentence dataset...")
    sentence_samples = load_from_existing_dataset('pinyin_dataset.json', max_samples // 2)
    for s in sentence_samples:
        key = s['hanzi']
        if key not in seen:
            seen.add(key)
            all_samples.append(s)
    print(f"  Total: {len(all_samples)} samples")

    # Limit to max samples
    if len(all_samples) > max_samples:
        all_samples = all_samples[:max_samples]

    # Save
    print(f"\nSaving {len(all_samples)} samples to {output_path}...")
    output_data = {
        'metadata': {
            'description': 'HMM pinyin-to-hanzi dataset (simplified Chinese)',
            'total_samples': len(all_samples),
            'simplified_only': True,
        },
        'data': all_samples
    }

    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(output_data, f, ensure_ascii=False, indent=2)

    file_size = os.path.getsize(output_path) / (1024 * 1024)

    # Stats
    length_stats = defaultdict(int)
    for s in all_samples:
        hanzi_len = len(s['hanzi'])
        if hanzi_len <= 4:
            length_stats['1-4'] += 1
        elif hanzi_len <= 8:
            length_stats['5-8'] += 1
        elif hanzi_len <= 15:
            length_stats['9-15'] += 1
        else:
            length_stats['16+'] += 1

    print("\n" + "="*60)
    print("DATASET CREATED")
    print("="*60)
    print(f"Output: {output_path} ({file_size:.2f} MB)")
    print(f"Total samples: {len(all_samples)}")
    print("\nLength distribution:")
    for key in ['1-4', '5-8', '9-15', '16+']:
        count = length_stats[key]
        pct = count / len(all_samples) * 100
        print(f"  {key} hanzi: {count} ({pct:.1f}%)")

    print("\nSample entries:")
    for s in all_samples[:5]:
        print(f"  {s['pinyin']} -> {s['hanzi']}")


if __name__ == "__main__":
    create_dataset()
