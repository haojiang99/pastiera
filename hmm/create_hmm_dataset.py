def to_simplified(text):
    """Convert traditional Chinese to simplified."""
    return ''.join(TRAD_TO_SIMP.get(c, c) for c in text)


def is_chinese(char):
    """Check if character is Chinese."""
    return '\u4e00' <= char <= '\u9fff'


def clean_text(text):
    """Clean text - keep only Chinese characters."""
    return ''.join(c for c in text if is_chinese(c))


def hanzi_to_pinyin_syllables(text):
    """Convert hanzi to space-separated pinyin syllables."""
    try:
        py_list = pinyin(text, style=Style.NORMAL, errors='ignore')
        return ' '.join([p[0] for p in py_list if p[0]])
    except Exception:
        return None


def process_sample(hanzi_text):
    """Process a text sample into pinyin-hanzi pair."""
    # Clean and convert to simplified
    hanzi = clean_text(to_simplified(hanzi_text))

    if not hanzi or len(hanzi) < 2:
        return None

    # Get pinyin syllables
    pinyin_str = hanzi_to_pinyin_syllables(hanzi)

    if not pinyin_str:
        return None

    # Verify 1:1 mapping
    syllables = pinyin_str.split()
    if len(syllables) != len(hanzi):
        return None

    return {'pinyin': pinyin_str, 'hanzi': hanzi}


