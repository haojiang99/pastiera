    // Build reverse mapping (Traditional to Simplified)
    private val traditionalToSimplified: Map<Char, Char> by lazy {
        simplifiedToTraditional.entries
            .filter { it.key != it.value }  // Only include characters that actually differ
            .associate { it.value to it.key }
    }

    /**
     * Converts a string from simplified Chinese to traditional Chinese.
     */
    fun toTraditional(text: String): String {
        if (text.isEmpty()) return text
        return text.map { char ->
            simplifiedToTraditional[char] ?: char
        }.joinToString("")
    }

    /**
     * Converts a string from traditional Chinese to simplified Chinese.
     */
    fun toSimplified(text: String): String {
        if (text.isEmpty()) return text
        return text.map { char ->
            traditionalToSimplified[char] ?: char
        }.joinToString("")
    }

    /**
     * Converts a list of candidate strings based on the mode.
     * @param candidates List of candidate strings
     * @param useTraditional If true, converts to traditional; if false, keeps simplified
     * @return Converted list of candidates
     */
    fun convertCandidates(candidates: List<String>, useTraditional: Boolean): List<String> {
        return if (useTraditional) {
            candidates.map { toTraditional(it) }
        } else {
            candidates
        }
    }

    /**
     * Converts a single character based on the mode.
     */
    fun convertChar(char: Char, useTraditional: Boolean): Char {
        return if (useTraditional) {
            simplifiedToTraditional[char] ?: char
        } else {
            char
        }
    }
